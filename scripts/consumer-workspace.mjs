import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import {
    existsSync,
    lstatSync,
    mkdirSync,
    mkdtempSync,
    readdirSync,
    readFileSync,
    realpathSync,
    rmSync,
    writeFileSync
} from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const reservedConsumerNames = ['reports', 'history', 'lint-format-review', 'typecheck-separation'];

const removalOptions = { recursive: true, force: true, maxRetries: 3, retryDelay: 100 };

function createExternalDirectory(repository) {
    // Only this checkout's generated directories are eligible for crash recovery.
    // A live PID (including one we cannot inspect) is always left alone.
    const project = createHash('sha256')
        .update(realpathSync(repository))
        .digest('hex')
        .slice(0, 16);
    const prefix = `scrollprogress-consumer-${project}-`;
    const pattern = new RegExp(`^${prefix}([1-9][0-9]*)-[A-Za-z0-9]{6}$`);
    for (const entry of readdirSync(os.tmpdir(), { withFileTypes: true })) {
        const match = entry.name.match(pattern);
        if (!entry.isDirectory() || !match) continue;
        try {
            process.kill(Number(match[1]), 0);
        } catch (error) {
            if (error.code !== 'ESRCH') continue;
            const stale = path.join(os.tmpdir(), entry.name);
            rmSync(stale, removalOptions);
            console.log(`Removed interrupted consumer: ${stale}`);
        }
    }

    return mkdtempSync(path.join(os.tmpdir(), `${prefix}${process.pid}-`));
}

export function createConsumerWorkspace(
    repository,
    closeServer = async () => {},
    { external = false, name = 'consumer' } = {}
) {
    assert(
        /^[a-z0-9][a-z0-9-]{0,47}$/.test(name),
        'Consumer name must use lowercase letters, digits or hyphens (1–48 characters).'
    );
    assert(
        !reservedConsumerNames.includes(name),
        `The name "${name}" is reserved for saved results. Choose another consumer name.`
    );
    assert(
        !external || name === 'consumer',
        '--name is only available for consumers inside the project.'
    );
    let directory;
    let lock;
    if (external) {
        directory = createExternalDirectory(repository);
    } else {
        const results = path.join(repository, 'test-results');
        mkdirSync(results, { recursive: true });
        assert.equal(
            realpathSync(results),
            path.join(realpathSync(repository), 'test-results'),
            'test-results must not be a symlink outside the project.'
        );
        directory = path.join(results, name);
        const marker = path.join(directory, '.scrollprogress-consumer');
        const markerContents =
            'Generated by ScrollProgress consumer checks. Contents are replaced on the next run.\n';
        if (!existsSync(directory)) {
            mkdirSync(directory);
            writeFileSync(marker, markerContents);
        }
        assert(
            lstatSync(directory).isDirectory() && !lstatSync(directory).isSymbolicLink(),
            'Consumer directory must not be a symlink.'
        );
        assert(
            existsSync(marker) && readFileSync(marker, 'utf8') === markerContents,
            `Refusing to replace an unrecognized directory: ${directory}`
        );
        lock = path.join(directory, '.running');
        try {
            mkdirSync(lock);
        } catch (error) {
            if (error.code !== 'EEXIST') throw error;
            throw new Error(
                `Consumer is already in use: ${directory}. Stop its server or use --name with another name. After a forced termination, delete this generated consumer directory before retrying.`,
                { cause: error }
            );
        }
    }
    let stopping = false;
    let cleaned = false;
    const signals = new Map();
    function cleanup() {
        if (cleaned) return;
        if (external) rmSync(directory, removalOptions);
        else rmSync(lock, removalOptions);
        cleaned = true;
        process.removeListener('exit', onExit);
        for (const [signal, listener] of signals) process.removeListener(signal, listener);
    }
    function onExit() {
        // Node exit handlers must be synchronous, including on uncaught errors.
        try {
            cleanup();
            console.log(
                external
                    ? `Removed temporary consumer: ${directory}`
                    : `Consumer files kept: ${directory}`
            );
        } catch (error) {
            console.error(`Cannot clean up consumer ${directory}:`, error.message);
            process.exitCode = 1;
        }
    }
    process.once('exit', onExit);
    for (const [signal, exitCode] of [
        ['SIGINT', 130],
        ['SIGTERM', 143],
        ['SIGHUP', 129]
    ]) {
        const listener = async () => {
            if (stopping) process.exit(exitCode);
            stopping = true;
            try {
                await closeServer();
            } catch (error) {
                console.error('Error closing the consumer server:', error);
            } finally {
                process.exit(exitCode); // onExit deletes the external consumer or releases the local lock.
            }
        };
        signals.set(signal, listener);
        process.on(signal, listener);
    }
    if (!external) {
        // The lock prevents another command from replacing a running browser's files.
        // Keep partial output on failure; it will be replaced by the next run.
        for (const entry of readdirSync(directory)) {
            if (entry !== '.running' && entry !== '.scrollprogress-consumer')
                rmSync(path.join(directory, entry), removalOptions);
        }
    }
    return { directory, cleanup };
}
